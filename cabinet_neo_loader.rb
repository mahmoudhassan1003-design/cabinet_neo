# encoding: UTF-8
# =============================================================================
# ملف التحميل الرئيسي للإضافة — يوضع مباشرة داخل مجلد Plugins في SketchUp
# =============================================================================
# هذا الملف هو نقطة الدخول الأولى (Entry Point) التي يقرأها SketchUp عند بدء
# التشغيل، وهو مسؤول فقط عن إنشاء كائن SketchupExtension وتسجيله، ثم تسليم
# السيطرة إلى ملف main.rb الداخلي.
#
# ملاحظة مهمة: كلاس SketchupExtension في SketchUp Ruby API لا يدعم الخاصية
# license= — الخصائص المدعومة هي: name, description, version, creator, copyright.
# =============================================================================

require 'sketchup.rb'
require 'extensions.rb'

module CabinetNeo
  # -------------------------------------------------------------------------
  # حارس ضد التحميل المزدوج (Idempotency Guard)
  # -------------------------------------------------------------------------
  # عند إعادة تحميل الإضافة أثناء التطوير عبر الـ Ruby Console، قد يُعاد
  # تنفيذ هذا الملف. نمنع تسجيل الامتداد أكثر من مرة باستخدام علم داخلي.
  # -------------------------------------------------------------------------
  unless defined?(@loader_initialized) && @loader_initialized
    @loader_initialized = true

    # -----------------------------------------------------------------------
    # حساب المسارات الفعلية بشكل آمن ومطلق
    # -----------------------------------------------------------------------
    # PLUGIN_ROOT  : مسار مجلد Plugins (المجلد الأب)
    # INTERNAL_DIR : مسار مجلد الإضافة الداخلي cabinet_neo/
    # MAIN_FILE    : مسار ملف main.rb داخل cabinet_neo/
    # -----------------------------------------------------------------------
    PLUGIN_ROOT  = File.dirname(__FILE__).freeze
    INTERNAL_DIR = File.join(PLUGIN_ROOT, 'cabinet_neo').freeze
    MAIN_FILE    = File.join(INTERNAL_DIR, 'main').freeze

    # -----------------------------------------------------------------------
    # إنشاء كائن الامتداد (SketchupExtension)
    # -----------------------------------------------------------------------
    # الوسيط الأول  : الاسم الظاهر في مدير الإضافات
    # الوسيط الثاني : مسار ملف main.rb الذي سيُحمَّل عند تفعيل الإضافة
    # -----------------------------------------------------------------------
    extension = SketchupExtension.new('Cabinet Neo', MAIN_FILE)

    # -----------------------------------------------------------------------
    # إسناد الخصائص الوصفية المدعومة رسمياً (Metadata)
    # -----------------------------------------------------------------------
    # نتجنب استدعاء أي setter غير موجود مثل license= لتجنب NoMethodError.
    # -----------------------------------------------------------------------
    extension.description = 'Professional Parametric Kitchen Cabinetry Design and Manufacturing Tool.'
    extension.version     = '1.0.0'
    extension.creator     = 'Cabinet Neo Team'
    extension.copyright   = "© #{Time.now.year} Cabinet Neo Team"

    # -----------------------------------------------------------------------
    # تسجيل الامتداد لدى SketchUp
    # -----------------------------------------------------------------------
    # الوسيط الثاني `true` يعني: قم بتحميل الإضافة تلقائياً عند بدء SketchUp.
    # -----------------------------------------------------------------------
    Sketchup.register_extension(extension, true)

    # رسالة تأكيد في الـ Console للتأكد من نجاح عملية التحميل الأولية
    puts '[Cabinet Neo] Loader registered successfully.'
  end
end